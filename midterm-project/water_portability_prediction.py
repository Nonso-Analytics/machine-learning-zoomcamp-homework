def evaluate_pipeline_model(pipeline, X_train, X_test, y_train, y_test, model_name):
    """Train and evaluate a single pipeline model"""

    # Train
    pipeline.fit(X_train, y_train)

    # Predictions
    y_pred = pipeline.predict(X_test)
    y_pred_proba = pipeline.predict_proba(X_test)[:, 1] if hasattr(pipeline, 'predict_proba') else None

    # Metrics
    accuracy = accuracy_score(y_test, y_pred)
    precision = precision_score(y_test, y_pred)
    recall = recall_score(y_test, y_pred)
    f1 = f1_score(y_test, y_pred)
    # Recall for class 0 (Not Potable)
    recall_not_potable = recall_score(y_test, y_pred, pos_label=0)
    roc_auc = roc_auc_score(y_test, y_pred_proba) if y_pred_proba is not None else None

    # Cross-validation (on pipeline)
    cv_scores = cross_val_score(pipeline, X_train, y_train, cv=5, scoring='f1')

    results = {
        'model_name': model_name,
        'accuracy': accuracy,
        'precision': precision,
        'recall': recall,
        'f1_score': f1,
        'recall_not_potable': recall_not_potable,
        'roc_auc': roc_auc,
        'cv_f1_mean': cv_scores.mean(),
        'cv_f1_std': cv_scores.std()
    }

    print(f"\n{model_name}:")
    print(f"  Accuracy:  {accuracy:.4f}")
    print(f"  Precision: {precision:.4f}")
    print(f"  Recall:    {recall:.4f}")
    print(f"  Recall Not Potable: {recall_not_potable:.4f}")
    print(f"  F1-Score:  {f1:.4f}")
    print(f"  ROC-AUC:   {roc_auc:.4f}" if roc_auc else "  ROC-AUC:   N/A")
    print(f"  CV F1:     {cv_scores.mean():.4f} (+/- {cv_scores.std():.4f})")

    return results, pipeline

def train_baseline_pipeline_models(X_train, X_test, y_train, y_test):
    """Train multiple baseline models wrapped in pipelines"""

    models = {
        'Logistic Regression': LogisticRegression(max_iter=1000, random_state=42),
        'Decision Tree': DecisionTreeClassifier(random_state=42),
        'Random Forest': RandomForestClassifier(n_estimators=100,
    max_depth=10,
    min_samples_split=5,
    min_samples_leaf=2,
    random_state=42,
    n_jobs=-1),
        'Gradient Boosting': GradientBoostingClassifier(random_state=42),
        'SVM': SVC(probability=True, random_state=42),
        'Naive Bayes': GaussianNB()
    }

    results = []
    trained_pipelines = {}

    for name, model in models.items():
        # Wrap each model in a pipeline (imputer + scaler + model)
        pipeline = Pipeline([
            ('imputer', KNNImputer(n_neighbors=5)),
            ('scaler', StandardScaler()),
            ('model', model)
        ])
        result, trained_pipeline = evaluate_pipeline_model(pipeline, X_train, X_test, y_train, y_test, name)
        results.append(result)
        trained_pipelines[name] = trained_pipeline

    # Create comparison DataFrame
    results_df = pd.DataFrame(results).sort_values('f1_score', ascending=False)
    # Select the best model name AFTER creating results_df
    best_model_name = results_df.iloc[0]['model_name']

    return results_df, trained_pipelines, best_model_name

