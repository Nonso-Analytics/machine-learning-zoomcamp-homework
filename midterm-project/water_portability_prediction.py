def tune_best_pipeline_model(X_train, y_train, best_model_name):
    """Perform hyperparameter tuning on the best model using a pipeline"""
    print(f"\nTuning: {best_model_name}")

    # Define model and parameter grid
    if best_model_name == 'Random Forest':
        model = RandomForestClassifier(random_state=42, n_jobs=-1)
        param_grid = {
            'model__n_estimators': [50, 100, 200],
            'model__max_depth': [5, 10, 15, None],
            'model__min_samples_split': [2, 5, 10],
            'model__min_samples_leaf': [1, 2, 4]
        }

    elif best_model_name == 'Gradient Boosting':
        model = GradientBoostingClassifier(random_state=42)
        param_grid = {
            'model__n_estimators': [50, 100, 200],
            'model__learning_rate': [0.01, 0.1, 0.2],
            'model__max_depth': [3, 5, 7],
            'model__min_samples_split': [2, 5, 10]
        }

    elif best_model_name == 'Logistic Regression':
        model = LogisticRegression(random_state=42, max_iter=1000)
        param_grid = {
            'model__C': [0.01, 0.1, 1, 10, 100],
            'model__penalty': ['l2'],
            'model__solver': ['lbfgs', 'liblinear']
        }

    else:
        print(f"No tuning implemented for {best_model_name}, using baseline")
        return None

    # Wrap in a pipeline
    pipeline = Pipeline([
        ('imputer', KNNImputer(n_neighbors=5)),
        ('scaler', StandardScaler()),
        ('model', model)
    ])

    # Grid Search
    print("Grid Search ...")
    grid_search = GridSearchCV(
        pipeline,
        param_grid,
        cv=5,
        scoring='f1',
        n_jobs=-1,
        verbose=1
    )

    grid_search.fit(X_train, y_train)

    print(f"\nBest parameters: {grid_search.best_params_}")
    print(f"Best CV F1-Score: {grid_search.best_score_:.4f}")

    return grid_search.best_estimator_

def final_evaluation_pipeline(pipeline, X_test, y_test, model_name="Final Model"):
    """Detailed evaluation of the final pipeline model"""

    # Predictions
    y_pred = pipeline.predict(X_test)
    y_pred_proba = pipeline.predict_proba(X_test)[:, 1] if hasattr(pipeline, 'predict_proba') else None

    # Metrics
    print(f"\n{model_name} Performance on Test Set:")
    print(f"Accuracy:  {accuracy_score(y_test, y_pred):.4f}")
    print(f"Precision: {precision_score(y_test, y_pred):.4f}")
    print(f"Recall:    {recall_score(y_test, y_pred):.4f}")
    print(f"F1-Score:  {f1_score(y_test, y_pred):.4f}")
    if y_pred_proba is not None:
        print(f"ROC-AUC:   {roc_auc_score(y_test, y_pred_proba):.4f}")
    else:
        print("ROC-AUC:   N/A")

    # Classification Report
    print("\nClassification Report:")
    print(classification_report(y_test, y_pred, target_names=['Not Potable', 'Potable']))

    # Confusion Matrix
    cm = confusion_matrix(y_test, y_pred)
    print("\nConfusion Matrix:")
    print(f"                Predicted")
    print(f"              Not   Potable")
    print(f"Actual Not    {cm[0,0]:<5} {cm[0,1]:<5}")
    print(f"       Potable {cm[1,0]:<5} {cm[1,1]:<5}")

    # Feature Importance
    model_inside = pipeline.named_steps.get('model', None)
    if model_inside is not None and hasattr(model_inside, 'feature_importances_'):
        feature_names = X_test.columns
        importance_df = pd.DataFrame({
            'feature': feature_names,
            'importance': model_inside.feature_importances_
        }).sort_values('importance', ascending=False)

        print("\nFeature Importance:")
        print(importance_df.to_string(index=False))

def main():
    """Main training pipeline"""

    # Train baseline models
    results_df, trained_models, best_model_name = train_baseline_pipeline_models(
        X_train, X_test, y_train, y_test
    )

    # Tune best model
    tuned_model = tune_best_pipeline_model(X_train, y_train, best_model_name)

    # Use tuned model if available, otherwise use baseline
    final_model = tuned_model if tuned_model else trained_models[best_model_name]

    # Final evaluation
    final_evaluation_pipeline(final_model, X_test, y_test, "Tuned Model" if tuned_model else "Baseline Model")

    # Save
    feature_names = X_train.columns.tolist()

    # Return results so they can be accessed
    return {
        "baseline_results": results_df,
        "trained_models": trained_models,
        "best_model_name": best_model_name,
        "tuned_model": tuned_model,
        "final_model": final_model,
        "feature_names": feature_names
    }

